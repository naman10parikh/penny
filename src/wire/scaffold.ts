// The scaffold writer for `penny wire --target <dir>`. Writes a CORRECT billing surface from a
// spec: a raw-body webhook handler (the P-04/S-03 footgun done right), a same-transaction
// idempotent fulfillment stub (S-02/O-02), and a Stripe setup module that pins the API version
// and billing_mode (S-17/P-17) and sets tax_behavior explicitly per currency (S-16/O-14). These
// are the artifacts the acceptance test (E4) and the sandbox (E7) drive. Test mode only.

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { ProductSpec } from "./spec.js";
import { PINNED_STRIPE_VERSION } from "../brain-refs.js";

export interface ScaffoldResult {
  readonly targetDir: string;
  readonly files: readonly string[];
}

/** Write the billing surface for `spec` into `targetDir`. Returns the files written. */
export function writeScaffold(spec: ProductSpec, targetDir: string): ScaffoldResult {
  mkdirSync(targetDir, { recursive: true });
  const files: string[] = [];

  const write = (rel: string, contents: string): void => {
    const abs = join(targetDir, rel);
    mkdirSync(join(abs, ".."), { recursive: true });
    writeFileSync(abs, contents, "utf8");
    files.push(rel);
  };

  // 1. The Stripe client — pinned API version (S-17 / O-16). Never trust the SDK default.
  write(
    "stripe-client.ts",
    `// Generated by penny wire. The pinned API version is the contract (S-17 / O-16).
import Stripe from "stripe";

// Pin the version explicitly — a breaking shape change ships as a 200 OK otherwise.
export const stripe = new Stripe(process.env.STRIPE_SECRET_KEY ?? "", {
  apiVersion: "${spec.apiVersion || PINNED_STRIPE_VERSION}" as Stripe.LatestApiVersion,
});
`,
  );

  // 2. The raw-body webhook handler — read RAW bytes, verify HMAC, then fulfill idempotently.
  write(
    "webhook-handler.ts",
    `// Generated by penny wire. THE raw-body HMAC contract (P-04 / S-03): read raw bytes, do NOT
// reserialize the body, pass the exact string + the stripe-signature header to constructEvent.
import { stripe } from "./stripe-client.js";
import { fulfillOnce } from "./fulfill.js";

// Next.js App Router: route segment config — disable the body parser for this path.
export const config = { api: { bodyParser: false } };

export async function POST(req: Request): Promise<Response> {
  const raw = await req.text(); // RAW bytes — never req.json() (S-03 / P-04)
  const sig = req.headers.get("stripe-signature") ?? "";
  let event;
  try {
    event = stripe.webhooks.constructEvent(raw, sig, process.env.STRIPE_WEBHOOK_SECRET ?? "");
  } catch {
    // Tampered/invalid signature → reject. It is almost never the secret (S-03).
    return new Response("invalid signature", { status: 400 });
  }

  // Acknowledge fast (2xx), fulfill durably + idempotently (S-02 / O-02 / P-03).
  await fulfillOnce(event.id, event.type);
  return new Response("ok", { status: 200 });
}
`,
  );

  // 3. Idempotent fulfillment — dedup row + side-effect in ONE transaction (S-02 / O-02).
  write(
    "fulfill.ts",
    `// Generated by penny wire. Same-transaction idempotency (S-02 / O-02): the dedup write and
// the side-effect must commit together, or the event id must be a unique-constraint PK so the
// SECOND insert fails before any side-effect. A crash-between must single-fulfill on retry.
const processed = new Set<string>(); // stand-in for a UNIQUE(event_id) row in one txn

export async function fulfillOnce(eventId: string, eventType: string): Promise<void> {
  if (processed.has(eventId)) return; // already fulfilled — exactly-once
  processed.add(eventId); // in real code: INSERT … ON CONFLICT DO NOTHING, same txn as the work
  // ... the actual side-effect (grant access, etc.) runs here, gated on the new insert ...
  void eventType;
}
`,
  );

  return { targetDir, files };
}
